const originalTextNodes = new WeakMap();
const originalAttributes = new WeakMap();

function dictionaryFor(language) {
  if (language === 'en') return translations.en;
  return {
    ...translations.en,
    ...translations[language],
    ...supplementalTranslations[language],
    ...complianceTranslations[language],
  };
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function translatePhrase(input, language) {
  if (!input || language === 'en') return input;
  const dict = dictionaryFor(language);
  const exact = dict[input.trim()];
  if (exact) return input.replace(input.trim(), exact);

  let output = input;
  const entries = Object.entries(dict)
    .filter(([key, value]) => key && value && key !== value && key.length > 2)
    .sort((a, b) => b[0].length - a[0].length);

  for (const [key, value] of entries) {
    const pattern = new RegExp(`(^|[^A-Za-z])(${escapeRegExp(key)})(?=$|[^A-Za-z])`, 'g');
    output = output.replace(pattern, (_, prefix) => `${prefix}${value}`);
  }
  return output;
}

function translateRenderedDom(language) {
  if (typeof document === 'undefined') return;

  const walker = document.createTreeWalker(
    document.body,
    NodeFilter.SHOW_TEXT,
    {
      acceptNode(node) {
        const parent = node.parentElement;
        if (!parent) return NodeFilter.FILTER_REJECT;
        if (['SCRIPT', 'STYLE', 'NOSCRIPT'].includes(parent.tagName)) return NodeFilter.FILTER_REJECT;
        if (parent.closest('[data-no-translate]')) return NodeFilter.FILTER_REJECT;
        if (!node.nodeValue || !/[A-Za-z]/.test(node.nodeValue)) return NodeFilter.FILTER_REJECT;
        return NodeFilter.FILTER_ACCEPT;
      },
    }
  );

  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach((node) => {
    if (!originalTextNodes.has(node)) originalTextNodes.set(node, node.nodeValue);
    const original = originalTextNodes.get(node);
    const nextValue = language === 'en' ? original : translatePhrase(original, language);
    if (node.nodeValue !== nextValue) node.nodeValue = nextValue;
  });

  document.querySelectorAll('input, textarea, select, [aria-label], [title]').forEach((el) => {
    const attrs = ['placeholder', 'aria-label', 'title'];
    attrs.forEach((attr) => {
      if (!el.hasAttribute(attr)) return;
      let stored = originalAttributes.get(el);
      if (!stored) {
        stored = {};
        originalAttributes.set(el, stored);
      }
      if (!stored[attr]) stored[attr] = el.getAttribute(attr);
      const original = stored[attr];
      const nextValue = language === 'en' ? original : translatePhrase(original, language);
      if (el.getAttribute(attr) !== nextValue) el.setAttribute(attr, nextValue);
    });
  });
}

const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => localStorage.getItem(STORAGE_KEY) || 'en');

  const setLanguage = (nextLanguage) => {
    const safeLanguage = translations[nextLanguage] ? nextLanguage : 'en';
    localStorage.setItem(STORAGE_KEY, safeLanguage);
    setLanguageState(safeLanguage);
  };

  useEffect(() => {
    document.documentElement.lang = language;
    let frame = 0;
    let timeout = 0;
    const translate = () => {
      cancelAnimationFrame(frame);
      frame = requestAnimationFrame(() => translateRenderedDom(language));
    };

    translate();
    timeout = window.setTimeout(translate, 500);

    const observer = new MutationObserver((mutations) => {
      if (!mutations.some((mutation) => mutation.addedNodes.length || mutation.type === 'characterData' || mutation.type === 'attributes')) return;
      translate();
    });

    observer.observe(document.body, {
      childList: true,
      subtree: true,
      characterData: true,
      attributes: true,
      attributeFilter: ['placeholder', 'aria-label', 'title'],
    });

    return () => {
      observer.disconnect();
      cancelAnimationFrame(frame);
      window.clearTimeout(timeout);
    };
  }, [language]);

  useEffect(() => {
    const nativeAlert = window.alert;
    const nativeConfirm = window.confirm;
    window.alert = (message) => nativeAlert(translatePhrase(String(message), language));
    window.confirm = (message) => nativeConfirm(translatePhrase(String(message), language));
    return () => {
      window.alert = nativeAlert;
      window.confirm = nativeConfirm;
    };
  }, [language]);

  const value = useMemo(() => ({
    language,
    setLanguage,
    t: (key) => dictionaryFor(language)?.[key] || translations.en[key] || key,
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error('useLanguage must be used inside LanguageProvider');
  return ctx;
}
